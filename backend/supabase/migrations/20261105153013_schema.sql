CREATE SCHEMA filmsuki;
REVOKE ALL ON SCHEMA filmsuki FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA filmsuki REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA filmsuki REVOKE ALL ON SEQUENCES FROM PUBLIC;

CREATE TABLE filmsuki.users (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL CHECK (char_length(btrim(username)) > 0),
    email VARCHAR(254) NOT NULL CHECK (email = btrim(email) AND char_length(email) > 0),
    password_hash TEXT NOT NULL CHECK (char_length(password_hash) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_unique ON filmsuki.users (lower(email));

CREATE TABLE filmsuki.movies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL CHECK (char_length(btrim(title)) > 0),
    year INTEGER NOT NULL CHECK (year > 0),
    director VARCHAR(255) NOT NULL CHECK (char_length(btrim(director)) > 0),
    genres TEXT[] NOT NULL CHECK (cardinality(genres) > 0),
    rating NUMERIC(3, 1) NOT NULL CHECK (rating BETWEEN 0 AND 10),
    duration VARCHAR(50) NOT NULL,
    synopsis TEXT NOT NULL,
    poster_url TEXT NOT NULL,
    cast_members TEXT[] NOT NULL
);

CREATE INDEX movies_genres_index ON filmsuki.movies USING gin (genres);

CREATE TABLE filmsuki.watchlists (
    user_id INTEGER NOT NULL REFERENCES filmsuki.users(id) ON DELETE CASCADE,
    movie_id INTEGER NOT NULL REFERENCES filmsuki.movies(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, movie_id)
);

CREATE INDEX watchlists_movie_id_index ON filmsuki.watchlists (movie_id);

CREATE TABLE filmsuki.reviews (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES filmsuki.users(id) ON DELETE CASCADE,
    movie_id INTEGER NOT NULL REFERENCES filmsuki.movies(id) ON DELETE RESTRICT,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review TEXT NOT NULL CHECK (char_length(btrim(review)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, movie_id)
);

CREATE INDEX reviews_movie_id_index ON filmsuki.reviews (movie_id);
CREATE INDEX reviews_user_history_index ON filmsuki.reviews (user_id, created_at DESC);
